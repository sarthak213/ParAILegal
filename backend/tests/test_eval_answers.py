import json
from pathlib import Path

from eval.answers import _SAYS_UNKNOWN, KEY_FACTS

QUESTIONS = Path(__file__).parents[1] / "eval" / "questions.jsonl"


def test_key_facts_belong_to_test_questions():
    if not QUESTIONS.exists():  # generated by python -m eval.build_questions
        return
    rows = {r["id"]: r for r in map(json.loads, QUESTIONS.read_text(encoding="utf-8").splitlines())}
    for qid in KEY_FACTS:
        assert qid in rows and rows[qid]["split"] == "test", qid


def test_says_unknown():
    for text in ("The provided sources do not identify the current Chief Justice.",
                 "These provisions don't directly cover parking rules.",
                 "The sources cannot determine the petrol price.",
                 "This is not covered by the sources."):
        assert _SAYS_UNKNOWN.search(text), text
    assert not _SAYS_UNKNOWN.search("Whoever commits murder shall be punished with death [1].")
